CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash TEXT NOT NULL,
    storage_path TEXT NOT NULL,
    mime TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    duration_ms BIGINT,
    title TEXT,
    description TEXT,
    is_favorite BOOLEAN NOT NULL DEFAULT FALSE
);
